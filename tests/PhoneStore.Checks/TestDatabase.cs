using Microsoft.Data.SqlClient;
using PhoneStore.Infrastructure.Data;

namespace PhoneStore.Checks;

internal sealed class TestDatabase : IAsyncDisposable
{
    public string ConnectionString { get; }
    private readonly string name;
    private readonly string masterConnection;

    private TestDatabase(SqlConnectionStringBuilder target)
    {
        name = "PhoneStore_QA_Rebuild_" + Guid.NewGuid().ToString("N");
        target.Pooling = false;
        masterConnection = new SqlConnectionStringBuilder(target.ConnectionString) { InitialCatalog = "master" }.ConnectionString;
        target.InitialCatalog = name;
        ConnectionString = target.ConnectionString;
    }

    public static async Task<TestDatabase> Create()
    {
        var configured = SqlTarget.Validate(Environment.GetEnvironmentVariable("PHONESTORE_TEST_CONNECTION"));
        var target = new SqlConnectionStringBuilder(configured);
        Check.True(target.InitialCatalog.StartsWith("PhoneStore_QA_", StringComparison.Ordinal), "Checks require a PhoneStore_QA_ target.");
        Check.True(target.DataSource == Environment.GetEnvironmentVariable("PHONESTORE_QA_SERVER") &&
            target.InitialCatalog == Environment.GetEnvironmentVariable("PHONESTORE_QA_DATABASE"), "QA target does not match explicit configuration.");
        var fixture = new TestDatabase(target);
        await using var master = new SqlConnection(fixture.masterConnection);
        await master.OpenAsync();
        await using var command = master.CreateCommand();
        command.CommandText = $"CREATE DATABASE [{fixture.name}]";
        await command.ExecuteNonQueryAsync();
        return fixture;
    }

    public async ValueTask DisposeAsync()
    {
        // The identifier was generated by this fixture, never taken from user configuration.
        await using var master = new SqlConnection(masterConnection);
        await master.OpenAsync();
        await using var cleanup = master.CreateCommand();
        cleanup.CommandText = $"DROP DATABASE [{name}]";
        await cleanup.ExecuteNonQueryAsync();
    }
}
